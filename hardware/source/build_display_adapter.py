def comp(ref,value,library,fp,x,y,pinmap,pinnames=None,angle=0):
 f=k.FootprintLoad(str(LIB/(library+'.pretty')),fp)
 if f is None:raise RuntimeError(fp)
 f.SetFPID(k.LIB_ID('MW_footprints',fp));f.SetReference(ref);f.SetValue(value);f.SetPosition(V(x,y));f.SetOrientationDegrees(angle)
