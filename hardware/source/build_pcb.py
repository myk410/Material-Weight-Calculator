  if p[0]!=last[0]:
   segment(anchor[1:],last[1:],last[0],name)
   via=k.PCB_VIA(b);via.SetPosition(V(last[1],last[2]));via.SetWidth(MM(1.0));via.SetDrill(MM(.5));via.SetViaType(k.VIATYPE_THROUGH);via.SetLayerPair(k.F_Cu,k.B_Cu);via.SetNet(nets[name]);b.Add(via)
   vias.append({'x':last[1],'y':last[2],'net':name})
   for l in (0,1):stamp(l,last[1],last[2],.5+trackwidth/2+clearance+.025,codes[name])
   anchor=p;direction=None
  else:
   dx=round(p[1]-last[1],6);dy=round(p[2]-last[2],6)
   nd=(0 if abs(dx)<1e-5 else math.copysign(1,dx),0 if abs(dy)<1e-5 else math.copysign(1,dy))
